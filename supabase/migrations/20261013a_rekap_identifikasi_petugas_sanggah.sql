-- 13 Okt 2026 -- Rekap identifikasi: siapa yang mengidentifikasi + sanggahan ("tidak terdampak" padahal terdampak).
-- Sudah diterapkan ke Supabase (migrasi 20261013a_rekap_identifikasi_petugas_sanggah dan 20261013b_sanggah_cabut_hak_anon). Berkas ini = salinan untuk repo.
-- Fungsi v2 TETAP ada (cadangan bila v3 gagal). Tabel hanya diakses lewat API (service_role); RLS aktif tanpa kebijakan, hak anon/authenticated dicabut.

create table if not exists public.bencana_identifikasi_sanggah (
  id bigint generated by default as identity primary key,
  idsubsls text not null,
  penyanggah_akun_id bigint not null references public.sigap_akun(id),
  alasan text not null check (char_length(alasan) between 10 and 500),
  dibuat_at timestamptz not null default now(),
  tanggapan text check (tanggapan is null or char_length(tanggapan) between 1 and 500),
  ditanggapi_oleh bigint references public.sigap_akun(id),
  ditanggapi_at timestamptz,
  hasil text check (hasil is null or hasil = 'tetap')
);
create index if not exists bencana_identifikasi_sanggah_subsls on public.bencana_identifikasi_sanggah (idsubsls);
-- satu penyanggah hanya boleh punya satu sanggahan TERBUKA per Sub SLS
create unique index if not exists bencana_identifikasi_sanggah_terbuka_unik on public.bencana_identifikasi_sanggah (idsubsls, penyanggah_akun_id) where ditanggapi_at is null;
alter table public.bencana_identifikasi_sanggah enable row level security;
revoke all on table public.bencana_identifikasi_sanggah from anon, authenticated;
revoke all on sequence public.bencana_identifikasi_sanggah_id_seq from anon, authenticated;

-- v3 = v2 + petugas (riwayat penyimpan dari sigap_audit 'identifikasi_simpan' + penyimpan terakhir), sanggah (status dihitung), pml_akun (pelaksana + pendamping SLS-nya).
-- Status sanggah: 'tetap' (PML/admin menanggapi) | 'dikoreksi' (Sub SLS diisi ulang sesudah sanggahan dan kini terdampak) | 'terbuka'.
create or replace function public.bencana_rekap_identifikasi_v3()
 returns table(idsubsls text, kecamatan text, nagari text, sls text, sub_sls text, tidak_terdampak boolean, sudah boolean, petugas jsonb, sanggah jsonb, pml_akun jsonb)
 language sql stable security definer set search_path to 'public'
as $function$
  with riw as (
    select a.detail->>'idsubsls' as idsubsls, a.akun_id, count(*)::int as n, max(a.waktu) as terakhir
      from public.sigap_audit a
     where a.aksi = 'identifikasi_simpan' and a.detail->>'idsubsls' is not null and a.akun_id is not null
     group by 1, 2
  ), gab as (
    select r.idsubsls, r.akun_id, r.n, r.terakhir from riw r
    union all
    select h.idsubsls, h.diisi_oleh_akun, 1, h.diisi_at from public.bencana_identifikasi_subsls h
     where h.diisi_oleh_akun is not null
       and not exists (select 1 from riw r where r.idsubsls = h.idsubsls and r.akun_id = h.diisi_oleh_akun)
  ), pt as (
    select g.idsubsls,
           jsonb_agg(jsonb_build_object('akun_id', g.akun_id, 'nama', coalesce(k.nama, '(tanpa nama)'), 'n', g.n, 'waktu', g.terakhir,
                                        'terakhir', g.akun_id is not distinct from h.diisi_oleh_akun) order by g.terakhir desc nulls last) as petugas
      from gab g
      left join public.sigap_akun k on k.id = g.akun_id
      left join public.bencana_identifikasi_subsls h on h.idsubsls = g.idsubsls
     group by g.idsubsls
  ), sg as (
    select s.idsubsls,
           jsonb_agg(jsonb_build_object('id', s.id, 'akun_id', s.penyanggah_akun_id, 'nama', coalesce(k.nama, '(tanpa nama)'), 'alasan', s.alasan, 'waktu', s.dibuat_at,
                                        'status', case when s.hasil = 'tetap' then 'tetap'
                                                       when h.diisi_at is not null and h.diisi_at > s.dibuat_at and coalesce(h.tidak_terdampak, false) = false then 'dikoreksi'
                                                       else 'terbuka' end,
                                        'tanggapan', s.tanggapan, 'oleh', k2.nama, 'waktu_tanggapan', s.ditanggapi_at) order by s.dibuat_at desc) as sanggah
      from public.bencana_identifikasi_sanggah s
      left join public.sigap_akun k on k.id = s.penyanggah_akun_id
      left join public.sigap_akun k2 on k2.id = s.ditanggapi_oleh
      left join public.bencana_identifikasi_subsls h on h.idsubsls = s.idsubsls
     group by s.idsubsls
  ), pa as (
    select al.idsls, jsonb_agg(distinct ak.id) as akun
      from public.bencana_identifikasi_alokasi al
      join public.sigap_akun ak on ak.petugas_bencana_id in (al.pml_pelaksana_id, al.pml_pendamping_id)
     group by al.idsls
  )
  select w.idsubsls, w.kecamatan, w.nagari, w.sls, w.sub_sls, coalesce(h.tidak_terdampak, false), (h.diisi_at is not null),
         coalesce(pt.petugas, '[]'::jsonb), coalesce(sg.sanggah, '[]'::jsonb), coalesce(pa.akun, '[]'::jsonb)
    from public.bencana_wilayah w
    left join public.bencana_identifikasi_subsls h on h.idsubsls = w.idsubsls
    left join pt on pt.idsubsls = w.idsubsls
    left join sg on sg.idsubsls = w.idsubsls
    left join pa on pa.idsls = left(w.idsubsls, 14)
   where exists (select 1 from public.bencana_identifikasi_alokasi a where a.idsls = left(w.idsubsls, 14)) or h.diisi_at is not null
   order by w.kecamatan, w.nagari, w.sls, w.sub_sls
$function$;
revoke all on function public.bencana_rekap_identifikasi_v3() from public, anon, authenticated;
grant execute on function public.bencana_rekap_identifikasi_v3() to service_role;
