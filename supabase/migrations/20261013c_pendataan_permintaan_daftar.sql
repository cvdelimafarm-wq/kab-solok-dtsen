-- meng-assign daftar KK ke FASIH. Admin menandai "sudah keluar di FASIH". Pembatalan/penyelesaian bersifat lunak (status), tidak ada yang dihapus.
-- Tabel hanya diakses lewat API (service_role); RLS aktif tanpa kebijakan, hak anon/authenticated dicabut.

create table if not exists public.bencana_pendataan_permintaan (
  id bigint generated by default as identity primary key,
  idsubsls text not null check (idsubsls ~ '^[0-9]{16}$'),
  pml_id bigint not null references public.bencana_petugas(id),
  ppl_akun_id bigint not null references public.sigap_akun(id),
  tanggal date not null,                       -- tanggal WIB saat diminta (dasar batas 2 Sub SLS per PML per hari)
  status text not null default 'menunggu' check (status in ('menunggu','sudah_keluar','dibatalkan')),
  diminta_oleh bigint not null references public.sigap_akun(id),
  diminta_at timestamptz not null default now(),
  selesai_oleh bigint references public.sigap_akun(id),
  selesai_at timestamptz,
  dibatalkan_oleh bigint references public.sigap_akun(id),
  dibatalkan_at timestamptz
);
create index if not exists bencana_pendataan_permintaan_pml on public.bencana_pendataan_permintaan (pml_id, tanggal);
create index if not exists bencana_pendataan_permintaan_status on public.bencana_pendataan_permintaan (status, diminta_at);
-- satu Sub SLS hanya boleh punya satu permintaan yang masih berlaku (menunggu / sudah keluar)
create unique index if not exists bencana_pendataan_permintaan_aktif_unik on public.bencana_pendataan_permintaan (idsubsls) where status in ('menunggu','sudah_keluar');
alter table public.bencana_pendataan_permintaan enable row level security;
revoke all on table public.bencana_pendataan_permintaan from anon, authenticated;
revoke all on sequence public.bencana_pendataan_permintaan_id_seq from anon, authenticated;

-- Simpan 1..2 permintaan sekaligus dengan batas per PML per hari diperiksa ATOMIK (kunci penasihat per PML) agar dua kiriman bersamaan tidak lolos 3 Sub SLS.
-- Hasil: {status:'ok', ids:[...]} | {status:'ditolak', alasan:'melebihi_batas'|'sudah_diminta', sisa:n}
create or replace function public.bencana_pendataan_minta(p_pml bigint, p_akun bigint, p_tanggal date, p_pilihan jsonb, p_maks int default 2)
 returns jsonb
 language plpgsql security definer set search_path to 'public'
as $function$
declare
  terpakai int;
  baru int;
  r jsonb;
  ids bigint[] := '{}';
  nid bigint;
begin
  baru := jsonb_array_length(p_pilihan);
  if baru < 1 then return jsonb_build_object('status','ditolak','alasan','kosong'); end if;
  perform pg_advisory_xact_lock(hashtextextended('pendataan_minta_' || p_pml::text, 0));
  select count(*) into terpakai from bencana_pendataan_permintaan where pml_id = p_pml and tanggal = p_tanggal and status <> 'dibatalkan';
  if terpakai + baru > p_maks then
    return jsonb_build_object('status','ditolak','alasan','melebihi_batas','sisa', greatest(p_maks - terpakai, 0));
  end if;
  for r in select * from jsonb_array_elements(p_pilihan) loop
    begin
      insert into bencana_pendataan_permintaan (idsubsls, pml_id, ppl_akun_id, tanggal, diminta_oleh)
      values (r->>'idsubsls', p_pml, (r->>'ppl_akun_id')::bigint, p_tanggal, p_akun) returning id into nid;
      ids := ids || nid;
    exception when unique_violation then
      raise exception 'SUDAH_DIMINTA';
    end;
  end loop;
  return jsonb_build_object('status','ok','ids', to_jsonb(ids));
exception when raise_exception then
  if sqlerrm = 'SUDAH_DIMINTA' then return jsonb_build_object('status','ditolak','alasan','sudah_diminta'); end if;
  raise;
end;
$function$;
revoke all on function public.bencana_pendataan_minta(bigint, bigint, date, jsonb, int) from public, anon, authenticated;
grant execute on function public.bencana_pendataan_minta(bigint, bigint, date, jsonb, int) to service_role;
