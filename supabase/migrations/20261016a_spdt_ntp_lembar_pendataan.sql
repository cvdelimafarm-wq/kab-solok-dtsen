-- (16 Okt 2026) SPDT NTP 2026 -- FASE 1: Lembar Pendataan (daftar KK + peta + navigasi), tahapan, dan peran Supervisor.
-- Dijalankan SENDIRI oleh pemilik di Supabase > SQL Editor (proyek nlwkpakyfprugqwklxiu). Satu transaksi; gagal = tidak ada yang berubah.
-- Tidak menghapus data apa pun. Aman diulang (idempotent).
--
-- Isi:
--  1) Tabel sigap_spdt_kk       : daftar KK sasaran + koordinat + PPL & PML (diisi oleh berkas 20261016b_spdt_ntp_kk_seed.sql)
--  2) Tabel sigap_spdt_buka     : catatan koordinat KK yang dibuka petugas per hari (bahan kolom "koordinat dibuka hari ini" di Monitoring)
--  3) Menu + peran "Supervisor SPDT NTP" dan pemberiannya kepada Mailani Putri (357), Arini Alva Syaadah (73), Faisal Siddiq (200)
--  4) Kegiatan induk "SPDT NTP 2026" dengan tahap 1 Lembar Pendataan dan tahap 2 Transport Lokal (isi translok = alur yang sudah ada;
--     alur laporan baru menyusul di Fase 2 setelah Bapak menyetujui)
--  5) Mengaktifkan kembali Sherli Handayani (akun 601 dan penugasan 137) -- permintaan pemilik (16 Okt 2026)

begin;

-- 1) daftar KK ---------------------------------------------------------------------------------------------------------
create table if not exists public.sigap_spdt_kk (
  id bigint generated by default as identity primary key,
  kegiatan_id bigint not null default 2 references public.sigap_kegiatan(id),
  urut integer not null,
  kode_wilayah text not null,
  kecamatan text not null,
  nagari text not null,
  jorong text not null,
  nama_kk text not null,
  anggota_lain text,
  alamat text,
  akurasi_m numeric,
  lat double precision not null,
  lng double precision not null,
  ppl_nama text not null,
  pml_nama text not null,
  ppl_akun_id bigint references public.sigap_akun(id),
  pml_akun_id bigint references public.sigap_akun(id),
  dibuat_at timestamptz not null default now()
);
create index if not exists sigap_spdt_kk_ppl_idx on public.sigap_spdt_kk (ppl_akun_id);
create index if not exists sigap_spdt_kk_pml_idx on public.sigap_spdt_kk (pml_akun_id);
alter table public.sigap_spdt_kk enable row level security;

-- 2) catatan koordinat dibuka ------------------------------------------------------------------------------------------
create table if not exists public.sigap_spdt_buka (
  id bigint generated by default as identity primary key,
  kk_id bigint not null references public.sigap_spdt_kk(id) on delete cascade,
  akun_id bigint not null references public.sigap_akun(id),
  tanggal date not null,            -- tanggal WIB
  pertama_at timestamptz not null default now(),
  terakhir_at timestamptz not null default now(),
  navigasi boolean not null default false,   -- true bila petugas menekan tombol Navigasi
  unique (kk_id, akun_id, tanggal)
);
create index if not exists sigap_spdt_buka_tgl_idx on public.sigap_spdt_buka (tanggal, akun_id);
alter table public.sigap_spdt_buka enable row level security;

-- 3) menu + peran Supervisor --------------------------------------------------------------------------------------------
insert into public.sigap_menu (kode, portal, nama, keterangan, urutan, aktif)
select 'spdt.supervisor', 'SPDT NTP', 'Supervisor SPDT NTP', 'Monitoring petugas, seluruh peta & daftar KK, kelola translok', 10, true
where not exists (select 1 from public.sigap_menu where kode = 'spdt.supervisor');

insert into public.sigap_peran (kode, nama, keterangan, butuh_lingkup, sistem)
select 'supervisor_spdt_ntp', 'Supervisor SPDT NTP', 'Memantau seluruh PPL & PML SPDT NTP: Monitoring, peta & daftar KK semua wilayah, kelola translok. Lingkup per kegiatan.', true, false
where not exists (select 1 from public.sigap_peran where kode = 'supervisor_spdt_ntp');

insert into public.sigap_peran_izin (peran_id, menu_kode, level)
select p.id, 'spdt.supervisor', 'kelola' from public.sigap_peran p
where p.kode = 'supervisor_spdt_ntp'
  and not exists (select 1 from public.sigap_peran_izin i where i.peran_id = p.id and i.menu_kode = 'spdt.supervisor');

insert into public.sigap_akun_peran (akun_id, peran_id, kegiatan_id)
select a.id, p.id, 2
from public.sigap_akun a
join public.sigap_peran p on p.kode = 'supervisor_spdt_ntp'
where a.id in (357, 73, 200)
  and not exists (select 1 from public.sigap_akun_peran x where x.akun_id = a.id and x.peran_id = p.id and x.kegiatan_id = 2);

-- 4) kegiatan induk + tahap ---------------------------------------------------------------------------------------------
insert into public.sigap_induk (kode, nama, pendek, ikon, kegiatan_ids, urutan)
values ('spdt_ntp', 'SPDT NTP 2026', 'SPDT NTP', 'grafik', '{2}', 2)
on conflict (kode) do nothing;

insert into public.sigap_tahap (induk_kode, kode, urutan, nama, uraian, isi) values
  ('spdt_ntp', 'lembar_pendataan', 1, 'Lembar Pendataan', 'Daftar KK sasaran, peta koordinat, dan navigasi ke lokasi (lembar bantu, tanpa isian).', '{spdt_lembar}'),
  ('spdt_ntp', 'translok',         2, 'Translok',         'Transport Lokal: hari kerja, laporan, dan foto dokumentasi.', '{"translok:2"}')
on conflict (induk_kode, kode) do nothing;

-- 5) aktifkan kembali Sherli Handayani ----------------------------------------------------------------------------------
-- Akun 601 juga ikut diaktifkan: sebelumnya aktif = false, sehingga penugasan saja tidak cukup untuk bisa masuk.
update public.sigap_akun set aktif = true where id = 601 and aktif = false;
update public.sigap_penugasan set aktif = true where id = 137 and kegiatan_id = 2 and aktif = false;

-- Pemeriksaan akhir; gagal = rollback otomatis
do $$
declare n_sup int; n_tahap int; n_sherli int;
begin
  select count(*) into n_sup from public.sigap_akun_peran x join public.sigap_peran p on p.id = x.peran_id
   where p.kode = 'supervisor_spdt_ntp' and x.kegiatan_id = 2 and x.akun_id in (357, 73, 200);
  select count(*) into n_tahap from public.sigap_tahap where induk_kode = 'spdt_ntp';
  select count(*) into n_sherli from public.sigap_penugasan p join public.sigap_akun a on a.id = p.akun_id where p.id = 137 and p.aktif and a.aktif;
  if n_sup <> 3 then raise exception 'Supervisor terpasang % (harapan 3)', n_sup; end if;
  if n_tahap <> 2 then raise exception 'Tahap SPDT NTP % (harapan 2)', n_tahap; end if;
  if n_sherli <> 1 then raise exception 'Penugasan Sherli belum aktif'; end if;
end $$;

commit;

