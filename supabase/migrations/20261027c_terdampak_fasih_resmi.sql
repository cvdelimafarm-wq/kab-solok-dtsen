-- 20261027c_terdampak_fasih_resmi.sql
-- (27 Okt 2026) Hasil identifikasi versi FASIH (Excel "Rekap Identifikasi SLS Pascabencana 2026", ditarik 26 Okt 2026) menjadi ACUAN RESMI Sub SLS yang didata:
-- 656 Sub SLS ada di FASIH: 198 TERDAMPAK, 458 tidak terdampak (3 di antaranya berstatus REJECTED oleh Admin Kabupaten; kodenya tetap dipakai).
-- Permintaan user: Lembar Pendataan, pengajuan ke FASIH, monitoring dan target hanya untuk Sub SLS terdampak, dan "cocok antara Excel dengan SIGAP".
--
-- Yang dilakukan (semua lunak: tidak ada data dihapus; alokasi, daftar KK, hasil pendataan dan permintaan lama tetap utuh):
--  1. Tabel acuan bencana_terdampak_fasih (idsubsls, terdampak, status FASIH) berisi 656 baris Excel. Dipakai untuk pemeriksaan "cocok dengan Excel" dan bila nanti diimpor ulang.
--  2. Seluruh Sub SLS yang BUKAN terdampak menurut Excel ditandai non aktif (bencana_wilayah.nonaktif) dengan alasan berawalan "FASIH:":
--       - yang ada di Excel sebagai tidak terdampak : "FASIH: tidak terdampak (identifikasi 26 Okt 2026)"
--       - yang tidak ada di Excel sama sekali       : "FASIH: tidak ada di hasil identifikasi (26 Okt 2026)"
--     Sub SLS yang sudah non aktif sebelumnya (Nagari Gantuang Ciri, 14 Sub SLS; semuanya juga tidak terdampak) dibiarkan dengan alasan lamanya.
--     Akibatnya: pemicu bencana_permintaan_tolak_nonaktif menolak permintaan BARU ke FASIH untuk Sub SLS itu; target dan monitoring (tim, korwil, Kelola) sudah
--     mengabaikan Sub SLS non aktif; aplikasi (kode baru) menyembunyikannya dari Lembar Pendataan & kartu Plotting tim.
--  3. Kolam wilayah: bencana_kolam_daftar() tidak lagi menampilkan Sub SLS non aktif (isi lain fungsi sama persis dengan 20261016c/e).
--  4. Catatan audit (sigap_audit).
--
-- TIDAK diubah: permintaan yang sudah diajukan (menunggu / sudah_keluar) tetap berlaku; KK yang sudah didata di Sub SLS tidak terdampak tetap tersimpan.
-- Aman dijalankan ulang (idempoten). Jalankan SETELAH 20261018a_wilayah_nonaktif.sql (sudah ada di produksi).
-- Mengaktifkan kembali satu Sub SLS (bila keputusan berubah), contoh:
--   update public.bencana_wilayah set nonaktif = false, nonaktif_alasan = null, nonaktif_at = null where idsubsls = '1303110007000101';
--   (dan ubah baris acuannya: update public.bencana_terdampak_fasih set terdampak = true where idsubsls = '1303110007000101';)

