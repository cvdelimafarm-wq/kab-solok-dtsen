alter table public.arsip_kode add column if not exists fungsi   text references public.arsip_fungsi(kode);
alter table public.arsip_kode add column if not exists induk    text;
alter table public.arsip_kode add column if not exists tingkat  smallint;
alter table public.arsip_kode add column if not exists sumber   text not null default 'tambahan';
do $c$ begin
  if not exists (select 1 from pg_constraint where conname = 'arsip_kode_sumber_ck') then
    alter table public.arsip_kode add constraint arsip_kode_sumber_ck check (sumber in ('perka99','tambahan'));
  end if;
end $c$;
