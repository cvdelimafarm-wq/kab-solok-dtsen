--   4. Register baru "pbj" untuk dokumen pengadaan barang/jasa, pola NNN/PPK-BPSKAB/SOLOK/K/tahun (bukan KKA), dan 22 nomor paket Susenas Maret + Seruti TW I 2026 dicatat.
-- Nomor yang sudah terbit TIDAK diubah (23 ST Seruti TW IV tetap B-1615..B-1637/13030/VS.220/2026, bertanda tangan).
-- Aman diulang.

