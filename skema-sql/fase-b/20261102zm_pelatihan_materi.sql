-- Hanya server (service role) yang membaca dan menulis: RLS aktif tanpa kebijakan. Tanpa tabel ini tab Instrumen tetap jalan (hanya berkas unduhan), video tidak memblokir apa pun.
-- Satu tabel progres dipakai bersama oleh video DAN tautan (tautan: selesai_at = saat pertama dibuka).

create table if not exists sigap_pelatihan_materi (
  id           bigint generated by default as identity primary key,
  kegiatan_id  bigint      not null references sigap_kegiatan(id) on delete cascade,
  urutan       integer     not null default 0,
  jenis        text        not null check (jenis in ('video','tautan')),
  judul        text        not null check (char_length(judul) between 3 and 160),
  url          text        not null check (url ~* '^https?://'),
  youtube_id   text,
  durasi_detik integer     check (durasi_detik is null or durasi_detik between 5 and 14400),
  wajib        boolean     not null default false,
  aktif        boolean     not null default true,
  dibuat_oleh  text,
  dibuat_at    timestamptz not null default now(),
  diubah_at    timestamptz not null default now(),
  check (jenis <> 'video' or youtube_id is not null)
);

create index if not exists sigap_pelatihan_materi_kegiatan_idx on sigap_pelatihan_materi (kegiatan_id, aktif, urutan, id);

create table if not exists sigap_pelatihan_materi_progres (
  materi_id         bigint      not null references sigap_pelatihan_materi(id) on delete cascade,
  akun_id           bigint      not null references sigap_akun(id),
  segmen            jsonb       not null default '[]'::jsonb,   -- bagian video yang benar-benar diputar: [[dari,sampai],...] dalam detik, sudah digabung
  detik_unik        integer     not null default 0 check (detik_unik >= 0),
  selesai_at        timestamptz,
  selesai_manual    boolean     not null default false,          -- true = peserta menekan "Saya sudah menonton" (cadangan), diberi tanda di Monitoring
  putar_terakhir_at timestamptz,
  dibuat_at         timestamptz not null default now(),
  diperbarui_at     timestamptz not null default now(),
  primary key (materi_id, akun_id),
  check (jsonb_typeof(segmen) = 'array')
);

create index if not exists sigap_pelatihan_materi_progres_akun_idx on sigap_pelatihan_materi_progres (akun_id);

alter table sigap_pelatihan_materi enable row level security;
alter table sigap_pelatihan_materi_progres enable row level security;

